def _scene(row: Sequence[object]) -> Mapping[str, object]:
    (number, family, title, weather, lighting, road, surface, actors, trigger,
     system_behavior, expected_behavior, risk, pair) = row
    actor_text = "、".join(actors)
    summary = (
        f"{weather}{lighting}的{road}，道路表面为{surface}，参与对象包括{actor_text}。"
        f"事件经过为：{trigger}。{system_behavior}；测试期望为：{expected_behavior}。"
        f"需要重点复核的合成风险是：{risk}。"
    )
    return {
        "scene_id": f"SCN-{number:03d}",
        "title": title,
        "summary": summary,
        "environment": {"weather": weather, "lighting": lighting, "road_type": road, "surface": surface},
        "actors": actors,
        "trigger": trigger,
        "system_behavior": system_behavior,
        "expected_behavior": expected_behavior,
        "risk": risk,
        "evidence": [f"合成感知摘要：{trigger}", f"合成控制摘要：{system_behavior}"],
        "tags": [family, weather, lighting, pair],
        "synthetic": True,
        "source_basis": "method-only",
    }


def _query(query_id: str, text: str, query_type: str, relevance: Mapping[str, int]) -> Mapping[str, object]:
    return {
        "query_id": query_id,
        "text": text,
        "query_type": query_type,
        "relevance": relevance,
        "answerable": any(grade >= 2 for grade in relevance.values()),
    }


