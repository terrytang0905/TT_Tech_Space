def _jsonl(records: Iterable[Mapping[str, object]]) -> bytes:
    text = "".join(json.dumps(record, ensure_ascii=False, sort_keys=True, separators=(",", ":")) + "\n" for record in records)
    return text.encode("utf-8")


def build_dataset_bytes() -> Dict[str, bytes]:
    return {
        "scenes.jsonl": _jsonl(_scene(row) for row in SCENE_FACTS),
        "dev_queries.jsonl": _jsonl(_query(*row) for row in DEV_QUERY_FACTS),
        "golden_queries.jsonl": _jsonl(_query(*row) for row in GOLDEN_QUERY_FACTS),
    }


def write_dataset(data_dir: Path, check: bool) -> None:
    generated = build_dataset_bytes()
    if check:
        mismatches = [name for name, content in generated.items() if not (data_dir / name).exists() or (data_dir / name).read_bytes() != content]
        if mismatches:
            raise SystemExit("dataset differs: " + ", ".join(mismatches))
        return
    data_dir.mkdir(parents=True, exist_ok=True)
    for name, content in generated.items():
        (data_dir / name).write_bytes(content)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    write_dataset(ROOT / "data", args.check)


if __name__ == "__main__":
    main()
